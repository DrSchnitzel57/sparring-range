"""Fixed appliance network rules — rendered by the installer, never by the API.

The inner bridge is a real isolated L2 segment.  Guests may talk to each
other (the scenario needs web↔DB and attacker→target paths) and to the
controller's ingest listener, and nothing else: forwarding to the appliance's
outer interface, management/LAN networks, the model service or any other
workload is dropped by the chain policy.  The appliance host initiates the
narrow management/verification paths it needs; a guest cannot manufacture
those connections.

These rules are plain text for the operator to install once.  There is no
runtime firewall API and no host shell endpoint.
"""

from __future__ import annotations

import re

from .manifest import ApplianceManifest

TABLE = "inet sr_appliance"
_TABLE_LINE = re.compile(
    r"^\s*(add table|delete table|table|flush|include)\s*(\S*)\s*(\S*)\s*")


def nft_scope_problems(text: str) -> list[str]:
    """Verify the rendered ruleset touches ONLY its own table (plan 18).

    The loader service feeds this file to `nft -f`; the file must therefore
    never contain `flush ruleset`, never name a foreign table, and never
    `include` other files (an include could smuggle in arbitrary host
    rules).  Only three table-bearing forms are legal, all scoped to
    ``inet sr_appliance``."""
    problems: list[str] = []
    for number, line in enumerate(text.splitlines(), 1):
        stripped = line.split("#", 1)[0].strip()
        if not stripped:
            continue
        if re.search(r"\bflush\s+ruleset\b", stripped, re.I):
            problems.append(f"line {number}: flush ruleset is forbidden")
        m = _TABLE_LINE.match(stripped)
        if not m:
            continue
        verb, family, name = m.group(1), m.group(2), m.group(3)
        if verb == "flush":
            problems.append(f"line {number}: bare flush is forbidden "
                            "(rules must be replaced atomically by table)")
        elif verb == "include":
            problems.append(f"line {number}: includes are forbidden "
                            "(the loader may load exactly this file)")
        elif f"{family} {name}".strip() not in (TABLE, "sr_appliance", ""):
            problems.append(f"line {number}: touches foreign table "
                            f"{family!r} {name!r}")
    if "add table inet sr_appliance" not in text:
        problems.append("ruleset does not declare its own table")
    # First-run idempotence: `delete table` of a missing table fails, so
    # the delete must follow the idempotent `add table`.
    add, delete = text.find("add table inet sr_appliance"), \
        text.find("delete table inet sr_appliance")
    if delete >= 0 and not 0 <= add < delete:
        problems.append("delete table must follow add table "
                        "(first-run idempotence)")
    return problems


def _set(name: str, values: list[str]) -> list[str]:
    return [f"    set {name} {{", "        type ipv4_addr",
            "        flags interval", "        elements = { "
            + ", ".join(values) + " }", "    }"]


def render_nftables(m: ApplianceManifest) -> str:
    n = m.network
    lan = [str(n.lan_cidr)]
    mgmt = [str(n.management_cidr)]
    rng = [str(n.range_cidr)]
    lines = [
        "#!/usr/sbin/nft -f",
        "# Generated by deploy/appliance.py from the manifest. Apply once as root.",
        "# Do not edit at runtime; regenerate and re-apply for a manifest change.",
        "add table inet sr_appliance",
        "delete table inet sr_appliance",
        "table inet sr_appliance {",
    ]
    lines += _set("management_v4", mgmt + lan)
    lines += _set("range_v4", rng)
    lines += [
        "    chain input {",
        "        type filter hook input priority filter; policy drop;",
        "        # Check guest ingress BEFORE conntrack and management allows.",
        f'        iifname "{n.range_bridge}" meta nfproto ipv6 counter drop',
        f'        iifname "{n.range_bridge}" ip saddr != @range_v4 counter drop',
        "        ct state established,related accept",
        "        iifname \"lo\" accept",
        "        # operator/browser/member edge only from management or LAN",
        f'        iifname != "{n.range_bridge}" ip saddr @management_v4 '
        'tcp dport { 22, 80, 443, 2222 } accept',
        f'        iifname != "{n.range_bridge}" ip saddr @management_v4 udp dport 53 accept',
        "        # guests reach ONLY the controller ingest listener",
        f"        iifname \"{n.range_bridge}\" ip saddr @range_v4 "
        f"ip daddr {n.controller_range_ip} tcp dport {n.ingest_port} accept",
        f"        iifname \"{n.range_bridge}\" ip saddr @range_v4 "
        f"ip daddr {n.bastion_address} tcp dport 2222 accept",
        "        # liveness probes from the trusted controller; no guest-originated",
        "        # connection can use these because the source set is the bridge",
        f"        iifname \"{n.range_bridge}\" ip saddr @range_v4 icmp type echo-request accept",
        "        ip protocol icmp icmp type echo-request limit rate 5/second accept",
        "        ip6 nexthdr icmpv6 icmpv6 type { echo-request, nd-neighbor-solicit, "
        "nd-neighbor-advert, nd-router-solicit, nd-router-advert } accept",
        "    }",
        "    chain forward {",
        "        type filter hook forward priority filter; policy drop;",
        f'        iifname "{n.range_bridge}" meta nfproto ipv6 counter drop',
        f'        iifname "{n.range_bridge}" ip saddr != @range_v4 counter drop',
        "        ct state established,related accept",
        f"        iifname \"{n.range_bridge}\" oifname \"{n.range_bridge}\" accept",
        "        # explicit denials for clarity and audit; the policy already drops",
        f"        iifname \"{n.range_bridge}\" ip daddr @management_v4 drop",
        f"        iifname \"{n.range_bridge}\" ip daddr "
        f"{n.range_cidr.network_address} drop",
        "    }",
        "    chain output {",
        "        type filter hook output priority filter; policy accept;",
        "        # host-initiated management/verification traffic is trusted and",
        "        # narrowly generated by fixed services; no runtime rule mutation.",
        "    }",
        "}",
    ]
    return "\n".join(lines) + "\n"


def render_networkd(m: ApplianceManifest) -> str:
    n = m.network
    return (
        "# /etc/systemd/network/10-srlab.netdev\n"
        "[NetDev]\n"
        f"Name={n.range_bridge}\n"
        "Kind=bridge\n"
        "\n"
        "# /etc/systemd/network/20-srlab.network\n"
        "[Match]\n"
        f"Name={n.range_bridge}\n"
        "[Network]\n"
        f"Address={n.controller_range_ip}/{n.range_cidr.prefixlen}\n"
        "ConfigureWithoutCarrier=yes\n"
        "LinkLocalAddressing=no\n"
        "IPv6AcceptRA=no\n"
        "IPMasquerade=no\n"
    )
